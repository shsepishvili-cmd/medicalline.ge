-- =============================================================================
-- 10_invoice_module.sql
-- Simple invoice module used by /invoice and the legacy /invoice.html page.
-- Run in Supabase Dashboard -> SQL Editor if the inv_* tables are missing.
-- =============================================================================

CREATE TABLE IF NOT EXISTS public.inv_clients (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  name        TEXT NOT NULL,
  company     TEXT,
  id_num      TEXT,
  phone       TEXT,
  email       TEXT,
  city        TEXT,
  address     TEXT
);

CREATE TABLE IF NOT EXISTS public.inv_products (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  code         TEXT,
  name         TEXT NOT NULL,
  category     TEXT,
  price        NUMERIC(12, 2) NOT NULL DEFAULT 0,
  currency     TEXT NOT NULL DEFAULT 'GEL',
  unit         TEXT,
  description  TEXT,
  vat_included BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS public.inv_invoices (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  number            TEXT NOT NULL UNIQUE,
  status            TEXT NOT NULL DEFAULT 'draft'
                    CHECK (status IN ('draft', 'sent', 'paid', 'overdue', 'cancelled')),
  client_id         BIGINT REFERENCES public.inv_clients(id) ON DELETE SET NULL,
  date              DATE,
  due               DATE,
  currency          TEXT NOT NULL DEFAULT 'GEL',
  terms             TEXT,
  vat_rate          NUMERIC(5, 2) NOT NULL DEFAULT 18,
  discount          NUMERIC(5, 2) NOT NULL DEFAULT 0,
  note              TEXT,
  bank              TEXT,
  payment_splits    JSONB NOT NULL DEFAULT '[]'::jsonb,
  sender_name       TEXT,
  sender_id_num     TEXT,
  sender_addr       TEXT,
  sender_email      TEXT,
  sender_phone      TEXT,
  items             JSONB NOT NULL DEFAULT '[]'::jsonb,
  subtotal          NUMERIC(12, 2) NOT NULL DEFAULT 0,
  discount_amount   NUMERIC(12, 2) NOT NULL DEFAULT 0,
  vat_amount        NUMERIC(12, 2) NOT NULL DEFAULT 0,
  total             NUMERIC(12, 2) NOT NULL DEFAULT 0,
  color             TEXT NOT NULL DEFAULT '#2563eb'
);

CREATE TABLE IF NOT EXISTS public.inv_settings (
  id    INTEGER PRIMARY KEY DEFAULT 1,
  data  JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS inv_clients_name_idx ON public.inv_clients (name);
CREATE INDEX IF NOT EXISTS inv_products_name_idx ON public.inv_products (name);
CREATE INDEX IF NOT EXISTS inv_invoices_created_idx ON public.inv_invoices (created_at DESC);
CREATE INDEX IF NOT EXISTS inv_invoices_status_idx ON public.inv_invoices (status);
CREATE INDEX IF NOT EXISTS inv_invoices_client_idx ON public.inv_invoices (client_id);

ALTER TABLE public.inv_clients ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inv_products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inv_invoices ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inv_settings ENABLE ROW LEVEL SECURITY;

-- The invoice app is protected by the site-level INVOICE_SECRET cookie.
-- These policies keep the existing legacy REST-based invoice.html working.
DROP POLICY IF EXISTS "invoice_anon_all_clients" ON public.inv_clients;
CREATE POLICY "invoice_anon_all_clients" ON public.inv_clients
  FOR ALL TO anon USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "invoice_anon_all_products" ON public.inv_products;
CREATE POLICY "invoice_anon_all_products" ON public.inv_products
  FOR ALL TO anon USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "invoice_anon_all_invoices" ON public.inv_invoices;
CREATE POLICY "invoice_anon_all_invoices" ON public.inv_invoices
  FOR ALL TO anon USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "invoice_anon_all_settings" ON public.inv_settings;
CREATE POLICY "invoice_anon_all_settings" ON public.inv_settings
  FOR ALL TO anon USING (true) WITH CHECK (true);

INSERT INTO public.inv_settings (id, data)
VALUES (1, '{}'::jsonb)
ON CONFLICT (id) DO NOTHING;
