// Pre-fills the form's category from a catalog product. Returns '' when there is
// no confident match, so staff choose by hand instead of getting a wrong guess.
export function suggestWarrantyCategory(product: { slug?: string | null; category_slug?: string | null }) {
  const slug = String(product.slug || '').toLowerCase()
  const bySlug: Array<[RegExp, number]> = [
    [/finscan|cbct/, 0],
    [/hyperlight|xline/, 1],
    [/nanopix/, 2],
    [/helios/, 3],
    [/acuvision|mediworks/, 4],
    [/fast-?(pack|fill)/, 6],
    [/hager/, 7],
    [/e-?sanit/, 8],
    [/philden/, 9],
    [/soga/, 10],
    [/brilliance/, 11],
    [/sidelab/, 14],
  ]
  const match = bySlug.find(([pattern]) => pattern.test(slug))
  if (match) return WARRANTY_CATEGORIES[match[1]].name
  if (product.category_slug === 'scan') return WARRANTY_CATEGORIES[3].name
  if (product.category_slug === 'endo') return WARRANTY_CATEGORIES[5].name
  return ''
}
