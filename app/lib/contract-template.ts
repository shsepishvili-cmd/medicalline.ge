function formatContractDateLong(value?: string | null) {
  const date = value ? new Date(value) : new Date()
  if (Number.isNaN(date.getTime())) return 'თარიღი: ____________'
  const months = ['იანვარი', 'თებერვალი', 'მარტი', 'აპრილი', 'მაისი', 'ივნისი', 'ივლისი', 'აგვისტო', 'სექტემბერი', 'ოქტომბერი', 'ნოემბერი', 'დეკემბერი']
  return `თარიღი: „${date.getDate()}“ „${months[date.getMonth()]}“ ${date.getFullYear()} წ.`
}

